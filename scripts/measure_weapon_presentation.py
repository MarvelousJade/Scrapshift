"""Read reference alpha bounds; export numbers only, retaining Scrapshift artwork."""
import json,re
from pathlib import Path
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]
REF=Path('E:/UnityProjects/brotato-(3.x)')
catalog=json.loads((ROOT/'Assets/Scrapshift/Content/Reference/starter-profiles.json').read_text())
ids=sorted(set(w['id'] for w in catalog['equipment']))
rows=[]
for weapon in ids:
    paths=list((REF/'weapons').rglob(weapon+'.tscn'))
    if len(paths)!=1:raise ValueError((weapon,paths))
    source=paths[0].read_text()
    sprite=re.search(r'\[node name="Sprite"[^\n]*\]\n(.*?)(?=\n\[|\Z)',source,re.S)[1]
    resource=re.search(r'texture = ExtResource\( (\d+) \)',sprite)[1]
    texture=re.search(r'path="res://([^"]+)" type="Texture" id='+resource+r'\]',source)[1]
    bounds=Image.open(REF/texture).convert('RGBA').getbbox()
    scale=re.search(r'scale = Vector2\( ([\d.]+), ([\d.]+) \)',sprite)
    sx,sy=map(float,scale.groups()) if scale else (1,1)
    length=max((bounds[2]-bounds[0])*sx,(bounds[3]-bounds[1])*sy)/100
    rows.append(dict(id=weapon,length=length,reference=texture,alphaBounds=bounds,bodyWidthRatio=round(length/.59,4)))
report=ROOT/'artifacts/presentation-boss-review';report.mkdir(parents=True,exist_ok=True)
(report/'weapon-measurements.json').write_text(json.dumps({'basis':'Visible alpha bounds, reference 100 px/world unit; body width 59 px. Own artwork retained. No blanket shrink factor.', 'weapons':rows},indent=2)+'\n')
cases='\n'.join(f'                case "{r["id"]}": return {r["length"]:.4f}f;' for r in rows)
(ROOT/'Assets/Scrapshift/Runtime/WeaponVisualMetrics.cs').write_text('''// Generated by scripts/measure_weapon_presentation.py; numeric reference dimensions only.
namespace Scrapshift
{
    public static class WeaponVisualMetrics
    {
        public static float Length(string id)
        {
            switch(id)
            {
'''+cases+'''
                default: return .65f;
            }
        }
    }
}
''')
print(f'Measured {len(rows)} families; length range {min(r["length"] for r in rows)}–{max(r["length"] for r in rows)} world units.')
